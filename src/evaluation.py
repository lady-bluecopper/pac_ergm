# Parameter diagnostics
# ---------------------------------------------------------------------------
def parameter_diagnostics(cfg, history, g_gof):
    """Standard errors and final-window diagnostics for theta and nu."""
    theta_hist = np.asarray(history["theta"], dtype=float)
    nu_hist = np.asarray(history["nu"], dtype=float)
    W = min(int(cfg.control.polyak_window), len(theta_hist))
    window = theta_hist[-W:]

    try:
        se_stat = theta_std_errors(g_gof)
    except np.linalg.LinAlgError:
        C = np.cov(np.asarray(g_gof, dtype=float), rowvar=False)
        warnings.warn("Singular GoF covariance; using a pseudo-inverse for theta standard errors.")
        se_stat = np.sqrt(np.diag(np.linalg.pinv(C)))

    # Batch-means Monte-Carlo uncertainty of the Polyak estimate.
    n_batches = max(2, W // 10)
    n_batches = min(n_batches, W)
    batch_means = np.asarray([b.mean(axis=0) for b in np.array_split(window, n_batches)])
    if len(batch_means) > 1:
        se_mc = batch_means.std(axis=0, ddof=1) / np.sqrt(len(batch_means))
    else:
        se_mc = np.zeros(window.shape[1], dtype=float)
    se_total = np.sqrt(se_stat ** 2 + se_mc ** 2)
    mc_pct = np.divide(
        100.0 * se_mc ** 2,
        se_total ** 2,
        out=np.zeros_like(se_total),
        where=se_total > 0,
    )

    half = max(1, W // 2)
    first = window[:half]
    second = window[half:]
    if len(second):
        drift = np.divide(
            second.mean(axis=0) - first.mean(axis=0),
            se_stat,
            out=np.full_like(se_stat, np.nan),
            where=se_stat > 0,
        )
    else:
        drift = np.full_like(se_stat, np.nan)

    return {
        "window": W,
        "se_statistical": np.asarray(se_stat, dtype=float),
        "se_monte_carlo": np.asarray(se_mc, dtype=float),
        "se_total": np.asarray(se_total, dtype=float),
        "mcmc_pct": np.asarray(mc_pct, dtype=float),
        "drift_in_se": np.asarray(drift, dtype=float),
        "nu_last": float(nu_hist[-1]),
        "nu_mean_window": float(nu_hist[-W:].mean()),
        "nu_median_window": float(np.median(nu_hist[-W:])),
        "nu_sd_window": float(nu_hist[-W:].std(ddof=1)) if W > 1 else 0.0,
    }


