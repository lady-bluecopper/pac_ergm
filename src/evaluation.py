def save_history(run_dir, cfg, spec, history):
    """Save every outer-loop iterate, including theta and g_bar components."""
    run_dir = Path(run_dir)
    labels = list(spec.labels)
    theta = np.asarray(history["theta"], dtype=float)
    nu = np.asarray(history["nu"], dtype=float)
    g_bar = np.asarray(history["g_bar"], dtype=float)
    coverage = np.asarray(history["coverage"], dtype=float)
    residual = np.asarray(history["residual"], dtype=float)
    n_done = len(coverage)

    t = np.arange(n_done)
    alpha = float(cfg.control.step_size) / (1.0 + float(cfg.estimation.get("theta_decay", 1.0)) * t)
    eta = float(cfg.estimation.nu_step) / (1.0 + float(cfg.estimation.nu_decay) * t)

    df = pd.DataFrame({
        "iter": np.arange(n_done + 1),
        "alpha_theta": np.r_[np.nan, alpha],
        "eta_nu": np.r_[np.nan, eta],
    })
    for j, label in enumerate(labels):
        df[f"theta_{label}"] = theta[:, j]
    df["nu"] = nu
    df["coverage"] = np.r_[np.nan, coverage]
    df["residual"] = np.r_[np.nan, residual]
    df["theta_updated"] = np.r_[False, coverage >= 0.5]
    for j, label in enumerate(labels):
        df[f"g_bar_{label}"] = np.r_[np.nan, g_bar[:, j]]
    df.to_csv(run_dir / "history.csv", index=False)


def evaluate_and_save(
    *, cfg, adj, nodes, edgecov, spec, g_obs,
    theta_final, nu_final, history, final_samples,
    run_dir, project_root, specification, calibration_info=None,
):
    """Run post-fit evaluation and write every non-plotting artifact used by Plots.

    ERGM and LOLOG results are loaded opportunistically from their standard
    output folders.  Their absence does not prevent the PAC run from being
    evaluated; re-running this function after those baselines exist will merge
    them into ``arrays.npz`` and the tables.
    """
    run_dir = Path(run_dir)
    project_root = Path(project_root)
    run_dir.mkdir(parents=True, exist_ok=True)
    labels = list(spec.labels)
    g_obs = np.asarray(g_obs, dtype=float)
    theta_final = np.asarray(theta_final, dtype=float)
    scale = np.asarray(cfg.pac.norm_scale, dtype=float)
    epsilon = float(cfg.pac.epsilon)

    print("\nPost-estimation evaluation (hard band) ...", flush=True)
    gof = sample_pac_gof(cfg, adj, g_obs, spec, theta_final, nu_final)
    g_gof = gof["g_samples"]
    pac_networks = gof["networks"]
    diagnostics = parameter_diagnostics(cfg, history, g_gof)

    # Optional baselines produced by the retained ERGM notebook / LOLOG R scripts.
    ergm = load_ergm_baseline(project_root, specification, g_obs=g_obs)
    ensure_lolog_baseline(project_root, specification, cfg)
    lolog = load_lolog_baseline(project_root, specification, adj.shape[0], spec)

    metrics: dict[str, Any] = {
        "epsilon": epsilon,
        "delta": float(cfg.pac.delta),
        "PAC": in_model_criteria(g_gof, g_obs, scale, epsilon),
    }
    if ergm is not None and ergm["simstats"].shape[1] == len(g_obs):
        metrics["ERGM"] = in_model_criteria(ergm["simstats"], g_obs, scale, epsilon)
        if ergm.get("status") is not None:
            metrics["ERGM"]["status"] = ergm["status"]
    if lolog is not None and lolog["stats"].shape[1] == len(g_obs):
        # These are PAC statistics recomputed on LOLOG networks.  Plots uses the
        # own-statistic JSON below for the reported LOLOG in-model criteria.
        metrics["LOLOG"] = in_model_criteria(lolog["stats"], g_obs, scale, epsilon)

    labels_to_float = lambda values: dict(zip(labels, map(float, values)))
    metrics["theta"] = {
        "polyak_window": int(diagnostics["window"]),
        "estimate": labels_to_float(theta_final),
        "se_statistical": labels_to_float(diagnostics["se_statistical"]),
        "se_monte_carlo_batch_means": labels_to_float(diagnostics["se_monte_carlo"]),
        "se_total": labels_to_float(diagnostics["se_total"]),
        "mc_pct_of_variance": labels_to_float(diagnostics["mcmc_pct"]),
        "drift_second_vs_first_half_in_se": labels_to_float(diagnostics["drift_in_se"]),
    }
    metrics["nu"] = {
        "used_in_gof": float(nu_final),
        "last": diagnostics["nu_last"],
        "mean_window": diagnostics["nu_mean_window"],
        "median_window": diagnostics["nu_median_window"],
        "sd_window": diagnostics["nu_sd_window"],
    }
    W = int(diagnostics["window"])
    metrics["coverage_estimation_window_mean"] = float(np.mean(history["coverage"][-W:]))

    with open(run_dir / "thesis_metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    # LOLOG own-statistic criteria, when its baseline exists.
    own_lolog = None
    if lolog is not None and int(specification) in (2, 3):
        own_lolog = lolog_own_metrics(
            cfg, adj, spec, edgecov, lolog["networks"], specification,
        )
        with open(run_dir / "lolog_own_metrics.json", "w", encoding="utf-8") as f:
            json.dump(own_lolog, f, indent=2)
        lolog["coefficients"].to_csv(run_dir / "lolog_coefficients.csv", index=False)

    # Coefficient table consumed by Plots.
    coef = pd.DataFrame({"term": labels, "estimate": theta_final})
    coef["se_statistical"] = diagnostics["se_statistical"]
    coef["se_monte_carlo"] = diagnostics["se_monte_carlo"]
    coef["se_total"] = diagnostics["se_total"]
    coef["mcmc_pct"] = diagnostics["mcmc_pct"]
    z = np.divide(theta_final, diagnostics["se_total"], out=np.full_like(theta_final, np.nan), where=diagnostics["se_total"] > 0)
    coef["z"] = z
    coef["signif"] = [_significance(v) if np.isfinite(v) else "" for v in z]
    if ergm is not None and len(ergm["coefficients"]) == len(coef):
        ecoef = ergm["coefficients"].reset_index(drop=True)
        coef["ergm_estimate"] = ecoef["estimate"].to_numpy()
        if "std_error" in ecoef:
            coef["ergm_se"] = ecoef["std_error"].to_numpy()
        if "p_value" in ecoef:
            coef["ergm_p"] = ecoef["p_value"].to_numpy()
    coef.to_csv(run_dir / "coefficients.csv", index=False)

    save_history(run_dir, cfg, spec, history)
    if nodes is not None and hasattr(nodes, "to_csv"):
        nodes.to_csv(run_dir / "nodes_used.csv", index=False)

    theta_hist = np.asarray(history["theta"], dtype=float)
    nu_hist = np.asarray(history["nu"], dtype=float)
    g_bar_hist = np.asarray(history["g_bar"], dtype=float)
    coverage_hist = np.asarray(history["coverage"], dtype=float)
    residual_hist = np.asarray(history["residual"], dtype=float)

    arrays: dict[str, np.ndarray] = {
        "labels": np.asarray(labels),
        "g_obs": g_obs,
        "theta": theta_hist,
        "nu": nu_hist,
        "g_bar": g_bar_hist,
        "coverage": coverage_hist,
        "residual": residual_hist,
        "final_samples_g": np.asarray(final_samples[0], dtype=float),
        "final_samples_in_band": np.asarray(final_samples[1], dtype=np.int8),
        "gof_samples": g_gof,
        "gof_networks": pac_networks,
        "se_statistical": diagnostics["se_statistical"],
        "se_monte_carlo": diagnostics["se_monte_carlo"],
        "se_total": diagnostics["se_total"],
    }
    if calibration_info is not None:
        arrays["calib_dists"] = np.asarray(calibration_info["dists"], dtype=float)
        arrays["calib_scale"] = np.asarray(calibration_info["scale"], dtype=float)
        arrays["calib_mean_ref"] = np.asarray(calibration_info["mean_ref"], dtype=float)
    if edgecov:
        for name, matrix in dict(edgecov).items():
            arrays[f"edgecov_{name}"] = np.asarray(matrix, dtype=float)

    if ergm is not None:
        arrays["ergm_simstats"] = np.asarray(ergm["simstats"], dtype=float)
        for key in ("indeg_sim", "outdeg_sim", "esp_sim"):
            if key in ergm:
                arrays[f"ergm_{key}"] = np.asarray(ergm[key], dtype=float)
    if lolog is not None:
        arrays["lolog_stats"] = np.asarray(lolog["stats"], dtype=float)
        arrays["lolog_networks"] = np.asarray(lolog["networks"], dtype=np.int8)

    np.savez_compressed(run_dir / "arrays.npz", **arrays)

    # Human-readable summary used by Plots for the final estimates/window.
    n_done = len(coverage_hist)
    summary = {
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "specification": int(specification),
        "model": str(cfg.model.statistic_terms),
        "git_commit": _git(project_root, "rev-parse", "--short", "HEAD"),
        "n_iter_done": int(n_done),
        "g_obs": labels_to_float(g_obs),
        "theta_final_polyak": labels_to_float(theta_final),
        "theta_last": labels_to_float(theta_hist[-1]),
        "polyak_window": W,
        "nu_final": float(nu_final),
        "nu_last": float(nu_hist[-1]),
        "nu_max": float(nu_hist.max()),
        "nu_max_at_iter": int(nu_hist.argmax()),
        "epsilon": epsilon,
        "norm_scale": labels_to_float(scale),
        "coverage_last": float(coverage_hist[-1]),
        "coverage_mean_polyak_window": float(np.mean(coverage_hist[-W:])),
        "residual_last": float(residual_hist[-1]),
        "n_theta_updates": int(np.sum(coverage_hist >= 0.5)),
        "gof_coverage": float(gof["coverage"]),
        "se_statistical": labels_to_float(diagnostics["se_statistical"]),
        "se_monte_carlo": labels_to_float(diagnostics["se_monte_carlo"]),
        "se_total": labels_to_float(diagnostics["se_total"]),
        "mcmc_pct": labels_to_float(diagnostics["mcmc_pct"]),
        "thesis_metrics": metrics,
        "ergm_status": ergm.get("status") if ergm is not None else None,
        "lolog_status": lolog.get("status") if lolog is not None else None,
    }
    with open(run_dir / "results_summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(
        f"Evaluation saved: GoF coverage={gof['coverage']:.3f}, "
        f"R={metrics['PAC']['R']:.3f}, ES={metrics['PAC']['ES']:.3f}"
    )
    if ergm is None:
        print(f"ERGM baseline not found in output/run_ERGM_spec_{int(specification)}; PAC outputs were saved without it.")
    if int(specification) in (2, 3) and lolog is None:
        name = "lolog_office" if int(specification) == 2 else "lolog_office_stars"
        print(f"LOLOG baseline not found in output/{name}; PAC outputs were saved without it.")

    return {
        "metrics": metrics,
        "diagnostics": diagnostics,
        "gof": gof,
        "ergm": ergm,
        "lolog": lolog,
        "lolog_own_metrics": own_lolog,
    }
