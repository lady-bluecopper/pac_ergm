# LOLOG in-model metrics on its own sufficient statistics
# ---------------------------------------------------------------------------
def _lolog_statistics(edgecov, stars, decay=0.5):
    labels = ["edges", "mutual", "gwesp_ITP"]
    if stars:
        labels += ["out_star2", "out_star3", "in_star2", "in_star3"]
    labels += [f"edgecov_{k}" for k in ("use", "team", "floor", "metric")]

    C = {k: np.asarray(v, dtype=float) for k, v in dict(edgecov).items()}

    def stats(A):
        A = np.asarray(A, dtype=float)
        # Cyclic shared partners (ITP in ergm terminology).
        sp = (A @ A).T[A == 1]
        vals = [
            A.sum(),
            np.sum(A * A.T) / 2.0,
            np.exp(decay) * np.sum(1.0 - (1.0 - np.exp(-decay)) ** sp),
        ]
        if stars:
            out_d = A.sum(axis=1)
            in_d = A.sum(axis=0)
            vals += [
                comb(out_d, 2).sum(), comb(out_d, 3).sum(),
                comb(in_d, 2).sum(), comb(in_d, 3).sum(),
            ]
        vals += [(A * C[k]).sum() for k in ("use", "team", "floor", "metric")]
        return np.asarray(vals, dtype=float)

    return labels, stats


def _null_probability_matrix(cfg, adj, pac_spec):
    """Same dyad-independent null used by ``calibrate_band``."""
    from sklearn.linear_model import LogisticRegression

    n = adj.shape[0]
    dyad_independent = [term for term in pac_spec.terms if term.dyad_independent]
    if not dyad_independent:
        raise ValueError("no dyad-independent term in the model: cannot build the null")

    base = np.zeros_like(adj)
    X, y = [], []
    for u in range(n):
        for v in range(n):
            if u == v:
                continue
            X.append([x for term in dyad_independent for x in term.delta(base, u, v, 1)])
            y.append(int(adj[u, v]))
    X = np.asarray(X, dtype=float)
    y = np.asarray(y)
    beta = LogisticRegression(
        fit_intercept=False, C=1e12, max_iter=5000, tol=1e-10,
    ).fit(X, y).coef_[0]

    logits = X @ beta
    P = np.zeros((n, n), dtype=float)
    idx = 0
    for u in range(n):
        for v in range(n):
            if u == v:
                continue
            P[u, v] = logits[idx]
            idx += 1
    P = 1.0 / (1.0 + np.exp(-P))
    np.fill_diagonal(P, 0.0)
    return P


def lolog_own_metrics(cfg, adj, pac_spec, edgecov, lolog_networks, specification):
    """Evaluate LOLOG on the sufficient statistics of its own specification.

    Spec. 2 uses cyclic GWESP; Spec. 3 additionally uses second/third-order
    in/out stars instead of geometrically weighted degrees.  Its band is
    recalibrated with the same dyad-independent null used for PAC-ERGM.
    """
    specification = int(specification)
    if specification not in (2, 3):
        return None
    labels, stats = _lolog_statistics(edgecov, stars=(specification == 3))

    P = _null_probability_matrix(cfg, adj, pac_spec)
    rng = np.random.default_rng(int(cfg.seed))
    B = int(cfg.pac.n_bootstrap)
    bootstrap_stats = np.zeros((B, len(labels)), dtype=float)
    for b in range(B):
        A = (rng.uniform(size=adj.shape) < P).astype(np.int64)
        np.fill_diagonal(A, 0)
        bootstrap_stats[b] = stats(A)

    scale = np.maximum(bootstrap_stats.std(axis=0), 1e-6)
    d_null = np.linalg.norm((bootstrap_stats - bootstrap_stats.mean(axis=0)) / scale, axis=1)
    epsilon = float(round(np.quantile(d_null, 1.0 - float(cfg.pac.delta)), 2))

    obs = stats(adj)
    G = np.asarray([stats(A) for A in lolog_networks], dtype=float)
    Z = (G - obs) / scale
    distances = np.linalg.norm(Z, axis=1)
    pair_term = 0.0 if len(Z) < 2 else 0.5 * float(pdist(Z).mean())

    return {
        "specification": specification,
        "description": "LOLOG evaluated on the sufficient statistics of its own model; the band is recalibrated with the PAC dyad-independent null.",
        "statistics": labels,
        "observed": dict(zip(labels, map(float, obs))),
        "band": {
            "epsilon": epsilon,
            "delta": float(cfg.pac.delta),
            "scale": dict(zip(labels, map(float, scale))),
            "n_bootstrap": B,
            "seed": int(cfg.seed),
        },
        "LOLOG": {
            "R": float(np.linalg.norm(Z.mean(axis=0))),
            "pi_A": float(np.mean(distances <= epsilon)),
            "ES": float(distances.mean() - pair_term),
            "n_sim": int(len(Z)),
            "mean_z": dict(zip(labels, np.round(Z.mean(axis=0), 3).tolist())),
        },
    }


