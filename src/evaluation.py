def _network_chain(
    A0, theta, nu, seed, n_networks, burnin, gap,
    g_obs, epsilon, norm, spec, proposal, p_nbhd, scale, penalty,
):
    """One long chain: burn in once, then retain networks ``gap`` steps apart."""
    rng = np.random.default_rng(seed)
    A = A0.copy()
    nets = []
    for j in range(int(n_networks)):
        _, _, A = run_mcmc_inner(
            A, theta, nu, g_obs, epsilon, norm,
            n_samples=1, spec=spec, rng=rng,
            burnin=int(burnin) if j == 0 else 0,
            proposal=proposal, p_nbhd=p_nbhd, scale=scale,
            interval=int(gap), penalty=penalty,
        )
        nets.append(A.copy())
    return nets


def sample_pac_gof(cfg, adj, g_obs, spec, theta, nu):
    """Sample sufficient statistics and networks from the fitted hard-band model.

    For the statistic GoF, this follows ``cfg.gof`` directly.  For network GoF,
    if ``cfg.gof.net_chains`` is present, networks are drawn from that many long
    independent chains (burn-in once per chain, then one network every
    ``net_gap`` steps).  Otherwise the legacy behavior is retained: each network
    is generated by a chain restarted from the observed graph.
    """
    scale = np.asarray(cfg.pac.norm_scale, dtype=float)
    epsilon = float(cfg.pac.epsilon)
    norm = str(cfg.pac.norm)
    proposal = str(cfg.proposal.kind)
    p_nbhd = float(cfg.proposal.p_nbhd)
    penalty = str(cfg.gof.penalty)
    theta = np.asarray(theta, dtype=float)
    nu = float(nu)

    # Sufficient-statistic GoF: one long chain.
    rng = np.random.default_rng(int(cfg.gof.seed))
    g_samples, in_band, _ = run_mcmc_inner(
        adj, theta, nu, g_obs, epsilon, norm,
        n_samples=int(cfg.gof.n_samples), spec=spec, rng=rng,
        burnin=int(cfg.gof.burnin), proposal=proposal, p_nbhd=p_nbhd,
        scale=scale, interval=int(cfg.gof.interval), penalty=penalty,
    )

    # Network GoF.
    n_networks = int(cfg.gof.n_networks)
    net_chains = int(cfg.gof.get("net_chains", 0) or 0)
    if net_chains > 0:
        per_chain = int(math.ceil(n_networks / net_chains))
        seeds = np.random.SeedSequence(int(cfg.gof.net_seed)).spawn(net_chains)
        executor = get_reusable_executor(max_workers=net_chains)
        futures = [
            executor.submit(
                _network_chain,
                adj, theta, nu, s, per_chain,
                int(cfg.gof.net_burnin), int(cfg.gof.net_gap),
                g_obs, epsilon, norm, spec, proposal, p_nbhd, scale, penalty,
            )
            for s in seeds
        ]
        networks = [A for f in futures for A in f.result()][:n_networks]
    else:
        # This is the behavior used by the original ukFaculty GoF helper.
        rng_net = np.random.default_rng(int(cfg.gof.net_seed))
        networks = []
        for _ in range(n_networks):
            _, _, A = run_mcmc_inner(
                adj, theta, nu, g_obs, epsilon, norm,
                n_samples=1, spec=spec, rng=rng_net,
                burnin=int(cfg.gof.net_burnin), proposal=proposal,
                p_nbhd=p_nbhd, scale=scale,
                interval=int(cfg.gof.net_gap), penalty=penalty,
            )
            networks.append(A.copy())

    return {
        "g_samples": np.asarray(g_samples, dtype=float),
        "in_band": np.asarray(in_band, dtype=np.int8),
        "coverage": float(np.mean(in_band)),
        "networks": np.asarray(networks, dtype=np.int8),
    }


