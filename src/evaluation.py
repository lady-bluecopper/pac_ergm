def load_ergm_baseline(project_root, specification, g_obs=None):
    """Load files written by ``notebooks/ERGM_estimation.ipynb`` if present."""
    run_dir = Path(project_root) / "output" / f"run_ERGM_spec_{int(specification)}"
    coef_file = run_dir / "coef.csv"
    stats_file = run_dir / "simstats.csv"
    if not coef_file.exists() or not stats_file.exists():
        return None

    out: dict[str, Any] = {
        "run_dir": run_dir,
        "coefficients": pd.read_csv(coef_file),
        "simstats": pd.read_csv(stats_file).to_numpy(dtype=float),
    }
    status_file = run_dir / "status.txt"
    if status_file.exists():
        out["status"] = status_file.read_text(encoding="utf-8").strip()

    gobs_file = run_dir / "gobs.csv"
    if gobs_file.exists():
        out["g_obs"] = pd.read_csv(gobs_file)["value"].to_numpy(dtype=float)
        if g_obs is not None and len(out["g_obs"]) == len(g_obs):
            if not np.allclose(out["g_obs"], np.asarray(g_obs, float), rtol=1e-4, atol=1e-3):
                warnings.warn(f"ERGM g_obs in {gobs_file} does not match the PAC statistics.")

    for filename, key in (
        ("indeg.csv", "indeg_sim"),
        ("outdeg.csv", "outdeg_sim"),
        ("esp.csv", "esp_sim"),
    ):
        p = run_dir / filename
        if p.exists():
            out[key] = pd.read_csv(p).to_numpy(dtype=float)
    return out


def _read_lolog_networks(simedges_file, n_nodes, status_file=None):
    df = pd.read_csv(simedges_file)
    if len(df) == 0:
        return np.empty((0, n_nodes, n_nodes), dtype=np.int8)

    n_sim = int(df["sim"].max()) + 1
    if status_file is not None and Path(status_file).exists():
        text = Path(status_file).read_text(encoding="utf-8")
        m = re.search(r"nsim:\s*(\d+)", text)
        if m:
            n_sim = int(m.group(1))

    nets = np.zeros((n_sim, n_nodes, n_nodes), dtype=np.int8)
    for sim, grp in df.groupby("sim"):
        nets[int(sim), grp["from"].to_numpy(int), grp["to"].to_numpy(int)] = 1
    return nets




def ensure_lolog_baseline(project_root, specification, cfg):
    """Run the standalone LOLOG R baseline when its saved files are missing.

    The old PAC notebooks used to perform this orchestration.  Keeping it here
    makes the PAC command-line run self-contained while ERGM remains in its
    separate notebook, as intended.
    """
    specification = int(specification)
    if specification == 2:
        out_dir = Path(project_root) / "output" / "lolog_office"
        script = Path(project_root) / "scripts" / "lolog_office_baseline.R"
    elif specification == 3:
        out_dir = Path(project_root) / "output" / "lolog_office_stars"
        script = Path(project_root) / "scripts" / "lolog_office_stars_baseline.R"
    else:
        return

    prefix = out_dir / "uni2005"
    coef_file = Path(str(prefix) + "_coef.csv")
    simedges_file = Path(str(prefix) + "_simedges.csv")
    if coef_file.exists() and simedges_file.exists():
        return

    rscript = shutil.which("Rscript")
    if rscript is None:
        warnings.warn("Rscript was not found; LOLOG baseline will not be generated.")
        return
    if not script.exists():
        warnings.warn(f"LOLOG script not found: {script}")
        return

    edgecov = cfg.data.get("edgecov", None)
    if not edgecov or "use" not in edgecov:
        warnings.warn("LOLOG baseline requires the office2005 edge-covariate matrices.")
        return

    out_dir.mkdir(parents=True, exist_ok=True)
    cov_dir = Path(str(cfg.data.edgecov["use"])).parent
    nsim = int(cfg.ergm.nsim)
    log_file = out_dir / "R_log.txt"
    print(f"LOLOG baseline not found; running {script.name} ...", flush=True)
    with open(log_file, "w", encoding="utf-8") as log:
        result = subprocess.run(
            [rscript, "--vanilla", str(script), str(cfg.data.edges_path), str(cov_dir),
             str(nsim), str(prefix)],
            stdout=log, stderr=subprocess.STDOUT, text=True,
        )
    if result.returncode != 0:
        warnings.warn(f"LOLOG baseline failed (exit {result.returncode}); see {log_file}")


def load_lolog_baseline(project_root, specification, n_nodes, spec):
    """Load the LOLOG baseline for Specifications 2 or 3, if it has been run."""
    specification = int(specification)
    if specification == 2:
        prefix = Path(project_root) / "output" / "lolog_office" / "uni2005"
    elif specification == 3:
        prefix = Path(project_root) / "output" / "lolog_office_stars" / "uni2005"
    else:
        return None

    coef_file = Path(str(prefix) + "_coef.csv")
