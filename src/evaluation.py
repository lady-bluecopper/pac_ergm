# ---------------------------------------------------------------------------
# Generic in-model criteria
# ---------------------------------------------------------------------------
def standardized_distances(G, g_obs, scale):
    """Euclidean distance from ``g_obs`` after componentwise standardization."""
    G = np.asarray(G, dtype=float)
    g_obs = np.asarray(g_obs, dtype=float)
    scale = np.asarray(scale, dtype=float)
    return np.linalg.norm((G - g_obs) / scale, axis=1)


def standardized_residual(G, g_obs, scale):
    """R = ||(mean(G) - g_obs) / scale||_2."""
    z = (np.asarray(G, dtype=float).mean(axis=0) - np.asarray(g_obs, dtype=float)) / np.asarray(scale, dtype=float)
    return float(np.linalg.norm(z))


def band_coverage(G, g_obs, scale, epsilon):
    """Fraction of simulated statistics inside the hard band."""
    return float(np.mean(standardized_distances(G, g_obs, scale) <= float(epsilon)))


def energy_score(G, g_obs, scale, max_n=5000, seed=0):
    """Energy score on standardized sufficient statistics; lower is better."""
    Z = (np.asarray(G, dtype=float) - np.asarray(g_obs, dtype=float)) / np.asarray(scale, dtype=float)
    if len(Z) == 0:
        return float("nan")
    if len(Z) > max_n:
        rng = np.random.default_rng(seed)
        Z = Z[rng.choice(len(Z), max_n, replace=False)]
    pair_term = 0.0 if len(Z) < 2 else 0.5 * float(pdist(Z).mean())
    return float(np.linalg.norm(Z, axis=1).mean() - pair_term)


def in_model_criteria(G, g_obs, scale, epsilon):
    """Return the three in-model criteria used in the paper."""
    G = np.asarray(G, dtype=float)
    return {
        "R": standardized_residual(G, g_obs, scale),
        "pi_A": band_coverage(G, g_obs, scale, epsilon),
        "ES": energy_score(G, g_obs, scale),
        "n_sim": int(len(G)),
    }


